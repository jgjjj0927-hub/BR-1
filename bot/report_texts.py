def get_random_text() -> str:
    """Возвращает случайный текст жалобы из общего пула."""
    import random as _random
    return _random.choice(GENERAL_TEXTS)


def get_mixed_texts(category_texts: list, count: int = 8) -> list:
    """
    Миксует тексты из категории с общим пулом.
    Возвращает список из count случайных текстов.
    """
    import random as _random
    combined = category_texts + GENERAL_TEXTS
    return _random.sample(combined, min(count, len(combined)))
